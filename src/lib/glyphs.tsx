import type { ComponentProps } from 'react';

export type GlyphProps = Omit<ComponentProps<'i'>, 'children'> & { size?: number | string; solid?: boolean };
export type Glyph = (props: GlyphProps) => React.JSX.Element;

function glyph(regular: string, solid: string | null = regular, turn?: number): Glyph {
  return function Glyph({ size, solid: filled, className, style, ...rest }) {
    const icon = filled && solid ? `fi-sr-${solid}` : `fi-rr-${regular}`;
    const cls = `fi ${icon}${className ? ` ${className}` : ''}`;
    const labelled = rest['aria-label'] !== undefined;
    return <i {...rest} className={cls} style={size === undefined && turn === undefined ? style : { fontSize: size, transform: turn === undefined ? undefined : `rotate(${turn}deg)`, ...style }} aria-hidden={labelled ? undefined : true} />;
  };
}

